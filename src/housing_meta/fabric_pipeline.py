"""Generate the Fabric deployment bundle: pipeline definition, notebook and Warehouse SQL.

Everything that has to agree across the three (parameter names, the Lakehouse
name, the procedure name) is defined once here, so they can't drift apart.

The pipeline is deliberately small:

    [Build staging]  notebook: build one province-year, stage it, refresh SQL endpoint
          | on success
    [Load warehouse] stored procedure audit.usp_load_run: QA gate, metadata history,
                     dimensions, facts (fails the run on blocking QA issues)

It's driven entirely by four pipeline parameters, which the calling tool sets.
"""

from __future__ import annotations

import base64
import json
import uuid
from dataclasses import dataclass
from importlib import metadata, resources

PLACEHOLDER = "<{}>"

# name, pipeline type, default, notebook activity type, stored-procedure type, description
PARAMETERS = [
    ("source_system", "string", "ON", "string", "String", "Province code, e.g. ON (matches province=XX in Files/raw)"),
    ("reference_year", "int", 2025, "int", "Int32", "Reference year (matches year=YYYY in Files/raw)"),
    ("metadata_release", "string", "current", "string", "String",
     "'current' or a folder name under Files/metadata/releases/"),
    ("mode", "string", "validate", "string", "String",
     "'validate' (QA only) or 'publish' (QA, then load the warehouse)"),
]
PROCEDURE = "[audit].[usp_load_run]"
NOTEBOOK_ACTIVITY = "Build staging"
PROCEDURE_ACTIVITY = "Load warehouse"


@dataclass
class Target:
    """Where the pipeline runs. Unknown values become <PLACEHOLDERS> to fill in later."""
    workspace_id: str = PLACEHOLDER.format("WORKSPACE_ID")
    notebook_id: str = PLACEHOLDER.format("NOTEBOOK_ID")
    warehouse_id: str = PLACEHOLDER.format("WAREHOUSE_ID")
    warehouse_endpoint: str = PLACEHOLDER.format("WAREHOUSE_SQL_ENDPOINT")  # xxxx.datawarehouse.fabric.microsoft.com
    warehouse_name: str = "wh_housing"
    lakehouse_name: str = "lh_housing"
    pipeline_name: str = "pl_housing_load"

    def placeholders(self) -> list[str]:
        return [k for k, v in vars(self).items() if isinstance(v, str) and v.startswith("<")]


def _expr(value: str) -> dict:
    return {"value": value, "type": "Expression"}


def _policy(timeout: str) -> dict:
    return {"timeout": timeout, "retry": 0, "retryIntervalInSeconds": 30,
            "secureOutput": False, "secureInput": False}


def pipeline_content(t: Target) -> dict:
    """The pipeline-content.json part of a Fabric DataPipeline item."""
    nb_params = {name: {"value": _expr(f"@pipeline().parameters.{name}"), "type": nb_type}
                 for name, _, _, nb_type, _, _ in PARAMETERS}
    nb_params["run_id"] = {"value": _expr("@pipeline().RunId"), "type": "string"}

    sp_params = {name: {"value": _expr(f"@pipeline().parameters.{name}"), "type": sp_type}
                 for name, _, _, _, sp_type, _ in PARAMETERS}
    sp_params["run_id"] = {"value": _expr("@pipeline().RunId"), "type": "String"}

    return {
        "properties": {
            "description": (
                "Load one province-year delivery: build + stage (notebook), then QA gate and "
                "warehouse load (stored procedure). Generated by `housing-fabric bundle`."
            ),
            "parameters": {
                name: {"type": ptype, "defaultValue": default}
                for name, ptype, default, _, _, _ in PARAMETERS
            },
            # One run at a time: further calls queue instead of racing on staging/warehouse.
            "concurrency": 1,
            "activities": [
                {
                    "name": NOTEBOOK_ACTIVITY,
                    "type": "TridentNotebook",
                    "dependsOn": [],
                    "policy": _policy("0.02:00:00"),
                    "typeProperties": {
                        "notebookId": t.notebook_id,
                        "workspaceId": t.workspace_id,
                        "parameters": nb_params,
                    },
                },
                {
                    "name": PROCEDURE_ACTIVITY,
                    "type": "SqlServerStoredProcedure",
                    "dependsOn": [{"activity": NOTEBOOK_ACTIVITY, "dependencyConditions": ["Succeeded"]}],
                    "policy": _policy("0.01:00:00"),
                    "typeProperties": {
                        "storedProcedureName": PROCEDURE,
                        "storedProcedureParameters": sp_params,
                    },
                    "linkedService": {
                        "name": t.warehouse_name,
                        "properties": {
                            "annotations": [],
                            "type": "DataWarehouse",
                            "typeProperties": {
                                "endpoint": t.warehouse_endpoint,
                                "artifactId": t.warehouse_id,
                                "workspaceId": t.workspace_id,
                            },
                        },
                    },
                },
            ],
        }
    }


def platform_file(t: Target) -> dict:
    """The .platform file used by Fabric git integration."""
    return {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/gitIntegration/platformProperties/2.0.0/schema.json",
        "metadata": {"type": "DataPipeline", "displayName": t.pipeline_name},
        "config": {"version": "2.0", "logicalId": str(uuid.uuid5(uuid.NAMESPACE_URL, t.pipeline_name))},
    }


def create_request(t: Target) -> dict:
    """Body for POST /v1/workspaces/{workspaceId}/items (create the pipeline with its definition)."""
    payload = base64.b64encode(json.dumps(pipeline_content(t)).encode()).decode()
    return {
        "displayName": t.pipeline_name,
        "description": "Housing metadata model: load one province-year",
        "type": "DataPipeline",
        "definition": {"parts": [
            {"path": "pipeline-content.json", "payload": payload, "payloadType": "InlineBase64"},
        ]},
    }


def run_request(source_system: str, reference_year: int, metadata_release: str = "current",
                mode: str = "validate") -> dict:
    """Body for POST .../items/{pipelineId}/jobs/instances?jobType=Pipeline."""
    return {"executionData": {"parameters": {
        "source_system": source_system.upper(),
        "reference_year": int(reference_year),
        "metadata_release": metadata_release,
        "mode": mode,
    }}}


def warehouse_sql(t: Target) -> dict[str, str]:
    """Warehouse scripts with the Lakehouse name filled in."""
    root = resources.files("housing_meta").joinpath("fabric_assets", "warehouse")
    return {
        f.name: f.read_text().replace("lh_housing.", f"{t.lakehouse_name}.")
        for f in sorted(root.iterdir(), key=lambda p: p.name) if f.name.endswith(".sql")
    }


def wheel_name() -> str:
    try:
        version = metadata.version("housing-meta")
    except metadata.PackageNotFoundError:  # pragma: no cover
        version = "0.0.0"
    return f"housing_meta-{version}-py3-none-any.whl"


def notebook(t: Target) -> dict:
    """The Fabric Python notebook (nb_housing_build) as .ipynb JSON."""
    def code(src: str, tags: list[str] | None = None) -> dict:
        cell = {"cell_type": "code", "execution_count": None, "outputs": [],
                "metadata": {"tags": tags} if tags else {}, "source": src.strip("\n").splitlines(True)}
        return cell

    def md(src: str) -> dict:
        return {"cell_type": "markdown", "metadata": {}, "source": src.strip("\n").splitlines(True)}

    param_lines = []
    for name, ptype, default, _, _, desc in PARAMETERS:
        param_lines.append(f"{name} = {json.dumps(default)}".ljust(36) + f"# {desc}")
    param_lines.append('run_id = ""'.ljust(36) + "# set by the pipeline (@pipeline().RunId)")

    cells = [
        md(f"""
# nb_housing_build

Builds **one province-year** delivery with the `housing_meta` package and stages it in
the default Lakehouse (`{t.lakehouse_name}`) for the Warehouse procedure `audit.usp_load_run`.

Called by the `{t.pipeline_name}` pipeline. You can also run it by hand: edit the
parameters cell and run all. Generated by `housing-fabric bundle`; regenerate rather than edit.
"""),
        code("\n".join(["# Parameters (the pipeline overrides these)"] + param_lines), tags=["parameters"]),
        code(f"""
# Settings for this workspace
LAKEHOUSE_ROOT = "/lakehouse/default"          # default Lakehouse = {t.lakehouse_name}
TABLES_DIR = f"{{LAKEHOUSE_ROOT}}/Tables"         # schema-enabled Lakehouse: f"{{LAKEHOUSE_ROOT}}/Tables/dbo"
WHEEL = f"{{LAKEHOUSE_ROOT}}/Files/lib/{wheel_name()}"
KEEP_STAGING_DAYS = 30                         # older staging runs are pruned
WORKSPACE_ID = ""                              # blank = read from the runtime context
LAKEHOUSE_ID = ""                              # blank = read from the runtime context
"""),
        code("%pip install --quiet {WHEEL}"),
        code("""
import json
import uuid

from housing_meta import fabric_api, fabric_run, staging

run_id = run_id or f"manual-{uuid.uuid4()}"
result = fabric_run.run_delivery(
    raw_dir=f"{LAKEHOUSE_ROOT}/Files/raw",
    meta_dir=fabric_run.metadata_dir(f"{LAKEHOUSE_ROOT}/Files", metadata_release),
    tables_dir=TABLES_DIR,
    source_system=source_system,
    reference_year=int(reference_year),
    run_id=run_id,
    metadata_release=metadata_release,
    mode=mode,
    keep_staging_days=KEEP_STAGING_DAYS,
)
print(json.dumps({k: v for k, v in result.items() if k != "qa"}, indent=2))
"""),
        md("""
Refresh the Lakehouse SQL endpoint so the Warehouse procedure sees this run's staging
rows straight away (otherwise metadata sync can lag behind the write).
"""),
        code("""
import notebookutils

ctx = notebookutils.runtime.context
result["endpoint_refresh"] = fabric_api.refresh_sql_endpoint(
    workspace_id=WORKSPACE_ID or ctx.get("currentWorkspaceId"),
    lakehouse_id=LAKEHOUSE_ID or ctx.get("defaultLakehouseId"),
    tables=staging.STAGING_TABLES,
    token=notebookutils.credentials.getToken("pbi"),
)
print(f"refreshed {len(result['endpoint_refresh'])} staging tables")
"""),
        code("notebookutils.notebook.exit(json.dumps(result, default=str))"),
    ]
    return {
        "cells": cells,
        "metadata": {
            "kernel_info": {"name": "jupyter", "jupyter_kernel_name": "python3.11"},
            "kernelspec": {"name": "jupyter", "display_name": "Jupyter", "language": "Jupyter"},
            "language_info": {"name": "python"},
            "microsoft": {"language": "python", "language_group": "jupyter_python"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
